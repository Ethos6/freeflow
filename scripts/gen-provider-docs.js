// Regenerates docs/providers.md from the catalog: `npm run docs`.
import fs from "node:fs";
import { PROVIDERS } from "../src/catalog.js";

const groups = [
  ["free", "Free tiers and free models", "Free allowances are set by each provider and change; check their pages for current limits."],
  ["plan", "Subscriptions and coding plans", "Use these under each plan's terms (several are for personal, interactive coding only)."],
  ["paid", "Pay as you go", ""],
  ["local", "Local servers", "No key needed. Start the server, then use the model id it reports."],
];
let out = `# Providers\n\nfreeflow ships with ${PROVIDERS.length} providers. Use a model as \`<provider>/<model id>\`, for example \`groq/llama-3.3-70b-versatile\`.\nKeys can be added in the admin page, with \`freeflow key <provider>\`, or through the environment variable listed.\n\n<!-- generated by scripts/gen-provider-docs.js; do not edit by hand -->\n`;
for (const [tier, title, blurb] of groups) {
  const list = PROVIDERS.filter((p) => p.tier === tier);
  out += `\n## ${title} (${list.length})\n\n${blurb ? blurb + "\n\n" : ""}| Provider | Id | Key variable | Example model | Notes |\n| --- | --- | --- | --- | --- |\n`;
  for (const p of list) {
    const name = p.keyUrl ? `[${p.name}](${p.keyUrl})` : p.name;
    const notes = [p.note, p.needs?.includes("accountId") ? "Also needs `CLOUDFLARE_ACCOUNT_ID` (or the account id field)." : "", p.needs?.includes("baseUrl") ? "Set the base URL." : "", p.format === "anthropic" ? "Native Messages API." : ""].filter(Boolean).join(" ");
    out += `| ${name} | \`${p.id}\` | ${p.env ? `\`${p.env}\`` : "none"} | \`${p.id}/${p.example}\` | ${notes} |\n`;
  }
}
out += `\n## Your own endpoint\n\nAny server that speaks the OpenAI Chat Completions API (vLLM, SGLang, LiteLLM, a company gateway) or the Anthropic Messages API can be added from **Providers → Custom endpoint**. Its id becomes the model prefix.\n`;
fs.writeFileSync(new URL("../docs/providers.md", import.meta.url), out);
console.log(`wrote docs/providers.md (${PROVIDERS.length} providers)`);
